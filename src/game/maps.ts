export interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface Bounds {
  l: number;
  t: number;
  r: number;
  b: number;
}

export interface MapDef {
  /** игровое поле: разные карты задают поле разного размера */
  bounds: Bounds;
  spawns: [{ x: number; y: number }, { x: number; y: number }];
  obstacles: Rect[];
}

const W = 1280;
const FULL: Bounds = { l: 40, t: 40, r: 1240, b: 680 };

/** Зеркало относительно вертикальной оси x = 640. */
const mirror = (r: Rect): Rect => ({ x: W - r.x - r.w, y: r.y, w: r.w, h: r.h });
/** Левая половина + её зеркало + центральные (самосимметричные) блоки. */
const sym = (left: Rect[], center: Rect[] = []): Rect[] => [...left, ...left.map(mirror), ...center];
const R = (x: number, y: number, w: number, h: number): Rect => ({ x, y, w, h });

